// Actual UI acceptance. One-time values stay in memory or the protected operator directory.
import { chromium } from '../../frontend/node_modules/playwright/index.mjs';
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { randomBytes } from 'node:crypto';
const privatePath = '.tools/operator/m10/browser-qa.json';
const out = 'docs/evidence/m10/browser';
if (existsSync(privatePath)) { console.log('BROWSER_ACCEPTANCE_ALREADY_STARTED_REVIEW_REQUIRED'); process.exit(1); }
const privateData = {email:'browser-qa@example.test',password:randomBytes(24).toString('base64url')};
writeFileSync(privatePath,JSON.stringify(privateData,null,2),{flag:'wx'});
const access = JSON.parse(readFileSync('.tools/operator/m10/access.json','utf8').replace(/^\uFEFF/,''));
const result = {checked_at:new Date().toISOString(),checks:[],tls_verification:'browser_default'};
let browser, step='start';
function savePrivate() {writeFileSync(privatePath,JSON.stringify(privateData,null,2));}
async function login(page,email,password) {
  await page.goto('https://dashboard-m10.urumi.test/login');
  await page.getByLabel('Email',{exact:true}).fill(email);
  await page.getByLabel('Password',{exact:true}).fill(password);
  const response=page.waitForResponse(r=>new URL(r.url()).pathname==='/api/v1/auth/login'&&r.request().method()==='POST');
  await page.getByRole('button',{name:'Log in',exact:true}).click();
  const reply=await response;
  if(reply.status()!==200) throw new Error('login');
  await page.getByRole('heading',{name:'Servers',exact:true}).waitFor();
  return (await reply.json()).user;
}
async function shot(page,name) {await page.screenshot({path:`${out}/${name}.png`,fullPage:true,mask:[page.locator('[data-sensitive]'),page.locator('input[type=password]')]});}
try {
  browser=await chromium.launch();
  const admin=await browser.newPage();
  step='admin_login';
  await login(admin,access.admin_email,access.admin_password);
  await admin.getByRole('link',{name:'Members',exact:true}).click();
  step='create_invitation_once';
  await admin.getByLabel('Invite email',{exact:true}).fill(privateData.email);
  await admin.getByRole('button',{name:'Create invitation',exact:true}).click();
  const invitation=admin.getByLabel('Private invitation link value',{exact:true});
  await invitation.waitFor();
  const inviteUrl=await invitation.inputValue();
  await admin.getByRole('button',{name:'Dismiss',exact:true}).click();
  await shot(admin,'invitation-masked');
  result.checks.push('admin_browser_invitation_created_and_one_time_value_masked');
  const member=await browser.newPage();
  step='redeem_invitation_once';
  await member.goto(inviteUrl);
  await member.getByRole('heading',{name:'Accept invitation',exact:true}).waitFor();
  result.invitation_fragment_cleared=!new URL(member.url()).hash;
  if(!result.invitation_fragment_cleared) throw new Error('fragment');
  await member.getByLabel('New password',{exact:true}).fill(privateData.password);
  await member.getByRole('button',{name:'Create account',exact:true}).click();
  await member.getByText('Account created. Log in with your email and new password.',{exact:true}).waitFor();
  await shot(member,'invitation-redeemed');
  result.checks.push('member_browser_invitation_redeemed');
  step='member_login';
  const user=await login(member,privateData.email,privateData.password);
  result.user_id=user.id;
  privateData.user_id=user.id; savePrivate();
  result.member_role=user.role;
  result.admin_navigation_hidden=await member.getByRole('link',{name:'Members',exact:true}).count()===0;
  if(user.role!=='member'||!result.admin_navigation_hidden) throw new Error('role');
  result.checks.push('member_browser_login_and_role_navigation');
  await member.getByRole('link',{name:'Keys',exact:true}).click();
  await member.getByRole('heading',{name:'Gateway keys',exact:true}).waitFor();
  step='issue_own_key_once';
  await member.getByLabel('Key label',{exact:true}).fill('Browser QA temporary key');
  const issuePromise=member.waitForResponse(r=>new URL(r.url()).pathname===`/api/v1/members/${user.id}/keys`&&r.request().method()==='POST');
  await member.getByRole('button',{name:`Issue key for ${privateData.email}`,exact:true}).click();
  const issue=await issuePromise;
  if(![200,201].includes(issue.status())) throw new Error('key_issue');
  const issued=await issue.json();
  privateData.raw_key=issued.raw_key; privateData.key_id=issued.id; savePrivate();
  result.key_id=issued.id;
  await member.getByLabel('One-time gateway key value',{exact:true}).waitFor();
  await member.getByRole('button',{name:'Dismiss',exact:true}).click();
  await shot(member,'own-key-issued-masked');
  result.checks.push('member_browser_own_key_issued');
  step='revoke_own_key_once';
  await member.getByRole('button',{name:'Revoke Browser QA temporary key',exact:true}).click();
  const revokePromise=member.waitForResponse(r=>new URL(r.url()).pathname===`/api/v1/members/${user.id}/keys/${issued.id}`&&r.request().method()==='DELETE');
  await member.getByRole('dialog').getByRole('button',{name:'Confirm',exact:true}).click();
  const revoked=await revokePromise;
  if(![200,204].includes(revoked.status())) throw new Error('key_revoke');
  await member.locator('li').filter({hasText:'Browser QA temporary key'}).filter({hasText:'Revoked'}).waitFor();
  await shot(member,'own-key-revoked');
  result.checks.push('member_browser_own_key_revoked');
  step='member_audit_view';
  await member.getByRole('link',{name:'Audit',exact:true}).click();
  await member.getByRole('heading',{name:'Audit',exact:true}).waitFor();
  await member.getByText('Your activity.',{exact:false}).waitFor();
  result.member_audit_admin_filter_hidden=await member.getByLabel('User UUID',{exact:true}).count()===0;
  await shot(member,'member-audit');
  result.checks.push('member_browser_own_audit_view');
  step='admin_registry_edit';
  await admin.getByRole('link',{name:'Servers',exact:true}).click();
  const row=admin.locator('tbody tr').filter({hasText:'inventory'});
  const editButton=row.getByRole('button',{name:/^Edit /});
  const originalName=(await editButton.innerText()).slice(5);
  await editButton.click();
  await admin.getByLabel('Name',{exact:true}).fill(originalName+' browser QA');
  let saved=admin.waitForResponse(r=>new URL(r.url()).pathname.startsWith('/api/v1/servers/')&&r.request().method()==='PATCH');
  await admin.getByRole('button',{name:'Save server',exact:true}).click();
  if((await saved).status()!==200) throw new Error('registry_save');
  await admin.getByRole('button',{name:`Edit ${originalName} browser QA`,exact:true}).waitFor();
  await shot(admin,'registry-edited');
  step='admin_registry_restore';
  await admin.getByRole('button',{name:`Edit ${originalName} browser QA`,exact:true}).click();
  await admin.getByLabel('Name',{exact:true}).fill(originalName);
  saved=admin.waitForResponse(r=>new URL(r.url()).pathname.startsWith('/api/v1/servers/')&&r.request().method()==='PATCH');
  await admin.getByRole('button',{name:'Save server',exact:true}).click();
  if((await saved).status()!==200) throw new Error('registry_restore');
  await admin.getByRole('button',{name:`Edit ${originalName}`,exact:true}).waitFor();
  result.registry_original_name_restored=true;
  await shot(admin,'registry-restored');
  result.checks.push('admin_browser_registry_name_edit_and_restore_credentials_kept');
  step='admin_audit_visible';
  await admin.getByRole('link',{name:'Audit',exact:true}).click();
  await admin.locator('article').first().waitFor();
  result.audit_visible_count=await admin.locator('article').count();
  await shot(admin,'admin-audit');
  result.checks.push('admin_browser_real_tool_audit_visible');
  result.status='PASS';
} catch {result.status='FAILED_REVIEW_BEFORE_RETRY';result.failure_step=step;}
finally {await browser?.close();}
writeFileSync(`${out}/ui-acceptance.json`,JSON.stringify(result,null,2)+'\n');
console.log(JSON.stringify({status:result.status,failure_step:result.failure_step,completed_checks:result.checks.length,registry_original_name_restored:result.registry_original_name_restored}));
